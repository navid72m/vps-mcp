"""The per-VPS memory folder: bootstrap, safe paths, atomic writes (research M5, M9, M10)."""

from __future__ import annotations

import contextlib
import errno
import os
import stat
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from vps_mcp.errors import ErrorCategory, VpsMcpError
from vps_mcp.memory import frontmatter
from vps_mcp.memory.notes import NAME_RE, Note, validate_name

README = """\
# vps-mcp memory

This folder is the persistent memory that vps-mcp shares with every assistant session that
connects to it (any MCP client). It lives on this machine only.

- `notes/`     - one Markdown note per file. Written by assistants through the memory tools,
                 and safe to edit, add or delete by hand.
- `generated/` - facts generated by the server from its configuration and history. Do not edit:
                 these files are overwritten.
- `archive/`   - notes that were "forgotten". Move a file back to `notes/` to restore it.

Keep this folder private. If you version it with git, use a private repository.
"""

SUBDIRS = ("notes", "generated", "archive")
MAX_FILE_BYTES = 1024 * 1024  # never read anything larger, whatever the configured note limit


@dataclass
class Malformed:
    file: str
    reason: str


@dataclass
class Loaded:
    notes: list[Note] = field(default_factory=list)
    malformed: list[Malformed] = field(default_factory=list)
    mismatches: list[str] = field(default_factory=list)

    def by_name(self) -> dict[str, Note]:
        return {n.name: n for n in self.notes}


def _failed(msg: str) -> VpsMcpError:
    return VpsMcpError(ErrorCategory.FAILED, msg)


class MemoryFolder:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        self.notes_dir = self.root / "notes"
        self.generated_dir = self.root / "generated"
        self.archive_dir = self.root / "archive"

    # ---------------------------------------------------------------- bootstrap

    def ensure(self) -> None:
        for d in (self.root, *(self.root / s for s in SUBDIRS)):
            if d.is_symlink():
                raise _failed(f"memory folder component is a symlink: {d.name}")
            d.mkdir(mode=0o700, parents=True, exist_ok=True)
            with contextlib.suppress(OSError):
                os.chmod(d, 0o700)
        readme = self.root / "README.md"
        if not readme.exists():
            self.write_atomic(readme, README)

    def writable_fs(self) -> bool:
        return all(
            os.access(d, os.W_OK | os.X_OK) for d in (self.root, self.notes_dir, self.archive_dir)
        )

    # -------------------------------------------------------------------- paths

    def note_path(self, name: str) -> Path:
        validate_name(name)
        path = self.notes_dir / f"{name}.md"
        if path.parent.resolve() != self.notes_dir.resolve():
            raise VpsMcpError(ErrorCategory.INVALID_INPUT, "note path escapes the memory folder")
        return path

    # ---------------------------------------------------------------------- I/O

    @staticmethod
    def read_text(path: Path) -> str:
        """Read a regular file without following symlinks."""
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        try:
            st = os.fstat(fd)
            if not stat.S_ISREG(st.st_mode):
                raise OSError(errno.EINVAL, "not a regular file")
            if st.st_size > MAX_FILE_BYTES:
                raise OSError(errno.EFBIG, "file too large")
            with os.fdopen(fd, "rb", closefd=False) as fh:
                return fh.read().decode("utf-8")
        finally:
            os.close(fd)

    def write_atomic(self, path: Path, text: str) -> None:
        if path.is_symlink():
            raise _failed(f"refusing to write through a symlink: {path.name}")
        tmp = path.with_name(f".{path.stem}.{os.getpid()}.tmp")
        try:
            fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
            with os.fdopen(fd, "wb") as fh:
                fh.write(text.encode("utf-8"))
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)
        except OSError as exc:
            with contextlib.suppress(OSError):
                tmp.unlink()
            raise _failed(f"could not write {path.name}: {exc.strerror or exc}") from None

    # -------------------------------------------------------------------- notes

    def read_note(self, name: str) -> Note | None:
        path = self.note_path(name)
        if not path.exists() and not path.is_symlink():
            return None
        try:
            text = self.read_text(path)
            note = Note.from_text(name, text, path.lstat().st_mtime)
        except (OSError, UnicodeDecodeError, frontmatter.FrontMatterError) as exc:
            raise _failed(f"note '{name}' is unreadable: {exc}") from None
        note.name = name
        return note

    def load_all(self) -> Loaded:
        out = Loaded()
        if not self.notes_dir.is_dir() or self.notes_dir.is_symlink():
            return out
        for path in sorted(self.notes_dir.iterdir()):
            if path.name.startswith(".") or path.suffix != ".md":
                continue
            rel = f"notes/{path.name}"
            if not NAME_RE.fullmatch(path.stem):
                out.malformed.append(Malformed(rel, "file name is not a valid note name"))
                continue
            if path.is_symlink():
                out.malformed.append(Malformed(rel, "symlinks are not followed"))
                continue
            try:
                note = Note.from_text(path.stem, self.read_text(path), path.stat().st_mtime)
            except (OSError, UnicodeDecodeError, frontmatter.FrontMatterError) as exc:
                reason = exc.strerror if isinstance(exc, OSError) and exc.strerror else str(exc)
                out.malformed.append(Malformed(rel, reason[:200]))
                continue
            if note.name != path.stem:
                out.mismatches.append(path.stem)
                note.name = path.stem
            out.notes.append(note)
        return out

    def write_note(self, note: Note) -> None:
        self.write_atomic(self.note_path(note.name), note.to_text())

    def archive(self, name: str) -> str:
        src = self.note_path(name)
        if src.is_symlink() or not src.is_file():
            raise VpsMcpError(ErrorCategory.NOT_FOUND, f"note '{name}' does not exist")
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S")
        dest = self.archive_dir / f"{name}.{stamp}.md"
        n = 1
        while dest.exists():
            n += 1
            dest = self.archive_dir / f"{name}.{stamp}-{n}.md"
        try:
            os.replace(src, dest)
        except OSError as exc:
            raise _failed(f"could not archive '{name}': {exc.strerror or exc}") from None
        return f"archive/{dest.name}"

    def counts(self, loaded: Loaded | None = None) -> dict[str, int]:
        loaded = loaded or self.load_all()

        def n(d: Path) -> int:
            return sum(1 for p in d.glob("*.md")) if d.is_dir() else 0

        return {
            "active": len(loaded.notes),
            "malformed": len(loaded.malformed),
            "archived": n(self.archive_dir),
            "generated": n(self.generated_dir),
        }

    # ---------------------------------------------------------------- generated

    def write_generated(self, filename: str, text: str) -> bool:
        """Write ``generated/<filename>`` only if the content (ignoring the stamp) changed."""
        path = self.generated_dir / filename
        if path.parent.resolve() != self.generated_dir.resolve():
            raise VpsMcpError(ErrorCategory.INVALID_INPUT, "bad generated file name")
        try:
            old = self.read_text(path) if path.is_file() else None
        except (OSError, UnicodeDecodeError):
            old = None
        if old is not None and _strip_stamp(old) == _strip_stamp(text):
            return False
        self.write_atomic(path, text)
        return True

    def generated_texts(self) -> dict[str, str]:
        out: dict[str, str] = {}
        if not self.generated_dir.is_dir():
            return out
        for path in sorted(self.generated_dir.glob("*.md")):
            with contextlib.suppress(OSError, UnicodeDecodeError):
                out[path.name] = self.read_text(path)
        return out


def _strip_stamp(text: str) -> str:
    first, _, rest = text.partition("\n")
    return rest if first.startswith("<!-- generated by vps-mcp") else text
