log = logging.getLogger(__name__)

# Successful calls to these tools refresh generated/*.md (research M6).
REFRESH_TOOLS = frozenset(
    {
        "list_services",
        "get_service_status",
        "start_service",
        "stop_service",
        "restart_service",
        "set_boot_start",
        "deploy_service",
        "update_service",
        "configure_service",
        "rollback_service",
        "remove_service",
        "run_job",
        "job_status",
        "cancel_job",
        "rehearse",
        "rehearsal_status",
        "cancel_rehearsal",
        "db_compare",
        "run_check",
        "deploy_from_gitlab",
        "rollback_deploy",
        "gitlab_write",
        "gitlab_ci",
    }
)
GENERATED_HEADER = "<!-- generated by vps-mcp at {ts}; do not edit, changes are overwritten -->"
MAX_TOOL_BRIEFING = 32000
MAX_MALFORMED_LISTED = 20


def _home_tilde(p: Path) -> str:
    home = str(Path.home())
    s = str(p)
    return "~" + s[len(home) :] if s == home or s.startswith(home + "/") else s


class MemoryService:
    def __init__(
        self,
        config: AppConfig,
        conn: sqlite3.Connection,
        audit: AuditStore,
        secrets: list[str],
    ) -> None:
        assert config.memory.path, "memory.path is resolved by the config loader"
        self.config = config
        self.settings = config.memory
        self.conn = conn
        self.audit = audit
        self.secrets = secrets
        self.folder = MemoryFolder(config.memory.path)
        self.last_refresh: str | None = None
        self.last_error: str | None = None
        self.connect_chars = 0

    # ----------------------------------------------------------------- briefing

    def _briefing(self, budget: int) -> tuple[bf.Briefing, Loaded, dict[str, int]]:
        loaded = self.folder.load_all()
        counts = self.folder.counts(loaded)
        env = derived.environment(self.config, derived.observations(self.conn))
        b = bf.build(
            env,
            derived.outcomes(self.conn),
            bf.note_sections(loaded.notes),
            derived.changes(self.conn, 5),
            counts,
            budget,
            utcnow(),
        )
        return b, loaded, counts

    def connect_instructions(self) -> str:
        """The connect-time briefing; never raises (contracts: 'Memory unavailable')."""
        try:
            self.folder.ensure()
            self.refresh()
            b, _, _ = self._briefing(self.settings.briefing_chars)
            self.connect_chars = len(b.text)
            return b.text
        except Exception as exc:  # noqa: BLE001 - the server must still start
            reason = exc.message if isinstance(exc, VpsMcpError) else exc.__class__.__name__
            self.last_error = f"briefing: {reason}"
            log.warning("memory unavailable: %s", reason)
            return f"Memory unavailable: {reason}. Call memory_health."

    def briefing(self, max_chars: int | None = None) -> dict[str, Any]:
        budget = max_chars or min(self.settings.briefing_chars * 4, MAX_TOOL_BRIEFING)
        b, _, counts = self._briefing(budget)
        return {
            "briefing": b.text,
            "omitted": b.omitted,
            "counts": {k: counts[k] for k in ("active", "malformed", "archived")},
            "generated_at": utcnow(),
        }

    # ------------------------------------------------------------- search/read

    def _generated_notes(self) -> list[Note]:
        out = []
        for fname, text in self.folder.generated_texts().items():
            stem = fname.removesuffix(".md")
            out.append(
                Note(
                    name=f"generated-{stem}",
                    type="fact",
                    title=f"Generated: {stem}",
                    body=text,
                    source="vps-mcp",
                )
            )
        return out

    def search(
        self,
        query: str = "",
        type: str | None = None,
        tag: str | None = None,
        include_generated: bool = False,
        limit: int = 10,
    ) -> dict[str, Any]:
        query = (query or "").strip()
        if len(query) > 200:
            raise invalid("query must be at most 200 characters")
        if not query and not type and not tag:
            raise invalid("give a query, a type or a tag")
        if type:
            validate_type(type)
        if not 1 <= limit <= 50:
            raise invalid("limit must be between 1 and 50")
        notes = self.folder.load_all().notes
        if include_generated:
            notes += self._generated_notes()
        results, total = rank(notes, query, type, tag, limit)
        return {"kind": "recorded_memory", "results": results, "total": total}

    def _backlinks(self, loaded: Loaded, name: str) -> list[str]:
        return sorted(
            n.name
            for n in loaded.notes
            if n.name != name and any(t == name for t, _ in links(n.body))
        )

    def read(self, name: str) -> dict[str, Any]:
        validate_name(name)
        loaded = self.folder.load_all()
        by_name = loaded.by_name()
        note = by_name.get(name)
        if note is None:
            suggestions = difflib.get_close_matches(name, list(by_name), n=3)
            raise VpsMcpError(
                ErrorCategory.NOT_FOUND,
                f"note '{name}' does not exist",
                extra={"suggestions": suggestions},
            )
        return {
            "note": note.to_dict(),
            "links": [
                {"name": t, "exists": ok and t in by_name} | ({} if ok else {"invalid": True})
                for t, ok in links(note.body)
            ],
            "backlinks": self._backlinks(loaded, name),
        }

    # ------------------------------------------------------------------- writes

    def _audit(
        self,
        action: str,
        params: dict[str, Any],
        session_id: str | None,
        outcome: str,
        err: VpsMcpError | None = None,
        started: float | None = None,
    ) -> int:
        return self.audit.record(
            session_id=session_id,
            action=action,
            service_name=None,
            kind=None,
            params=params,
            confirmed=outcome != "preview",
            outcome=outcome,
            error_category=err.category.value if err else None,
            error_message=err.message if err else None,
            duration_ms=int((time.monotonic() - started) * 1000) if started else 0,
        )

    def _guarded(
        self, action: str, params: dict[str, Any], session_id: str | None, fn: Any
    ) -> dict[str, Any]:
        started = time.monotonic()
        try:
            if not self.settings.writable:
                raise VpsMcpError(
                    ErrorCategory.READ_ONLY, "memory writes are disabled in [memory] (writable)"
                )
            result: dict[str, Any] = fn()
        except VpsMcpError as err:
            outcome = "failed" if err.category is ErrorCategory.FAILED else "refused"
            self._audit(action, params, session_id, outcome, err, started)
            raise
        if not result.get("preview"):
            result["audit_id"] = self._audit(action, params, session_id, "success", None, started)
        return result

    def write(
        self,
        *,
        name: str | None,
        type: str | None,
        title: str | None,
        body: str | None,
        tags: list[str] | None,
        status: str | None,
        expected_updated: str | None,
        source: str | None,
        session_id: str | None,
    ) -> dict[str, Any]:
        params = {
            "name": name or (slugify(title) if isinstance(title, str) else None),
            "type": type,
        }

        def do() -> dict[str, Any]:
            nm = validate_name(name) if name is not None else None
            if nm is None:
                nm = slugify(validate_title(title))
            params["name"] = nm
            existing = self.folder.read_note(nm)
            if existing is None:
                if type is None:
                    raise invalid("type is required when creating a note")
                if title is None:
                    raise invalid("title is required when creating a note")
            elif expected_updated is not None and expected_updated != existing.updated:
                raise VpsMcpError(
                    ErrorCategory.CONFLICT,
                    "the note changed since you read it; merge with the current version",
                    extra={"current": existing.to_dict()},
                )
            ntype = validate_type(type) if type is not None else existing.type  # type: ignore[union-attr]
            masked = 0
            new_title = existing.title if existing and title is None else validate_title(title)
            new_title, n = mask_note(new_title, self.config.policy.secret_keys, self.secrets)
            masked += n
            new_body = existing.body if existing and body is None else (body or "")
            new_body, n = mask_note(new_body, self.config.policy.secret_keys, self.secrets)
            masked += n
            new_tags = existing.tags if existing and tags is None else validate_tags(tags)
            kept = []
            for t in new_tags:
                _, n = mask_note(t, self.config.policy.secret_keys, self.secrets)
                masked += n
                if not n:
                    kept.append(t)
            st = validate_status(status)
            now = now_iso()
            note = Note(
                name=nm,
                type=ntype,
                title=new_title,
                body=new_body.strip("\n"),
                tags=kept,
                created=existing.created if existing else now,
                updated=now,
                source=(source or "unknown")[:64],
                status=st if st is not None else (existing.status if existing else None),
                extra=existing.extra if existing else {},
            )
            size = len(note.to_text().encode("utf-8"))
            if size > self.settings.max_note_bytes:
                raise invalid(
                    f"note is {size} bytes; the limit is {self.settings.max_note_bytes}",
                    limit=self.settings.max_note_bytes,
                    size=size,
                )
            if existing is None:
                active = len(self.folder.load_all().notes)
                if active >= self.settings.max_notes:
                    raise invalid(
                        f"memory holds {active} notes; the limit is {self.settings.max_notes}. "
                        "Archive or merge notes first.",
                        limit=self.settings.max_notes,
                        active=active,
                    )
            self.folder.ensure()
            self.folder.write_note(note)
            out: dict[str, Any] = {
                "name": nm,
                "created": existing is None,
                "updated_at": now,
                "masked": masked,
                "path_hint": f"notes/{nm}.md",
            }
            if self.config.policy.read_only:
                out["read_only_policy"] = True
                out["note"] = "Saved: memory writes are local and allowed in read-only mode."
            return out

        return self._guarded("memory_write", params, session_id, do)

    def archive(self, name: str, confirm: bool, session_id: str | None) -> dict[str, Any]:
        params = {"name": name}

        def do() -> dict[str, Any]:
            validate_name(name)
            loaded = self.folder.load_all()
            note = loaded.by_name().get(name)
            if note is None:
                raise VpsMcpError(ErrorCategory.NOT_FOUND, f"note '{name}' does not exist")
            params["type"] = note.type
            backlinks = self._backlinks(loaded, name)
            if not confirm:
                return {
                    "preview": True,
                    "name": name,
                    "title": note.title,
                    "type": note.type,
                    "backlinks": backlinks,
                    "message": "Call again with confirm=true to archive this note.",
                }
            return {
                "name": name,
                "archived_as": self.folder.archive(name),
                "backlinks": backlinks,
            }

        return self._guarded("memory_archive", params, session_id, do)

    # ------------------------------------------------------------------- health

    def health(self) -> dict[str, Any]:
        root = self.folder.root
        exists = root.is_dir()
        loaded = self.folder.load_all()
        return {
            "folder": _home_tilde(root),
            "exists": exists,
            "enabled": self.settings.enabled,
            "writable": self.settings.writable,
            "writable_fs": exists and self.folder.writable_fs(),
            "counts": self.folder.counts(loaded),
            "malformed": [
                {"file": m.file, "reason": m.reason}
                for m in loaded.malformed[:MAX_MALFORMED_LISTED]
            ],
            "name_mismatches": loaded.mismatches,
            "limits": {
                "max_notes": self.settings.max_notes,
                "max_note_bytes": self.settings.max_note_bytes,
                "briefing_chars": self.settings.briefing_chars,
            },
            "last_refresh": self.last_refresh,
            "last_error": self.last_error,
            "connect_briefing_chars": self.connect_chars,
        }

    # ------------------------------------------------------------ derived facts

    def observe(self, tool: str, payload: dict[str, Any]) -> None:
        if tool == "list_services":
            items = payload.get("services") or []
        elif tool == "get_service_status":
            items = [payload.get("service")] if payload.get("service") else []
        else:
            return
        now = utcnow()
        for s in items:
            if not isinstance(s, dict) or not s.get("name") or not s.get("state"):
                continue
            self.conn.execute(
                "INSERT INTO service_observations (name, kind, state, observed_at) "
                "VALUES (?,?,?,?) ON CONFLICT(name, kind) DO UPDATE SET "
                "state=excluded.state, observed_at=excluded.observed_at",
                (str(s["name"]), str(s.get("kind") or "os"), str(s["state"]), now),
            )

    def refresh(self) -> None:
        """Rewrite generated/*.md from config + state DB. Never raises."""
        try:
            self.folder.ensure()
            head = GENERATED_HEADER.format(ts=utcnow())
            env = derived.environment(self.config, derived.observations(self.conn))
            outs = derived.outcomes(self.conn, 10, 10, 10) or ["- none yet"]
            chg = derived.changes(self.conn, 20) or ["- none yet"]
            files = {
                "environment.md": f"{head}\n# Environment\n\n{env}\n",
                "outcomes.md": f"{head}\n# Latest outcomes\n\n" + "\n".join(outs) + "\n",
                "changes.md": f"{head}\n# Recent changes\n\n" + "\n".join(chg) + "\n",
            }
            for fname, text in files.items():
                self.folder.write_generated(fname, text)
            self.last_refresh = utcnow()
        except Exception as exc:  # noqa: BLE001 - refresh is best effort
            reason = exc.message if isinstance(exc, VpsMcpError) else repr(exc)
            self.last_error = f"refresh: {reason}"
            log.warning("memory refresh failed: %s", reason)

    def after_tool(self, tool: str, payload: dict[str, Any]) -> None:
        if tool not in REFRESH_TOOLS:
            return
        try:
            self.observe(tool, payload)
        except Exception as exc:  # noqa: BLE001
            self.last_error = f"observe: {exc!r}"
            log.warning("memory observe failed: %r", exc)
        self.refresh()
