"""MemoryFolder: bootstrap, safe paths, atomic writes, loading, archive (T011)."""

from __future__ import annotations

import os
import stat
from pathlib import Path

import pytest

from tests.unit.memory.conftest import note_text, seed_notes
from vps_mcp.errors import VpsMcpError
from vps_mcp.memory.folder import MemoryFolder
from vps_mcp.memory.notes import Note


def mode(p: Path) -> int:
    return stat.S_IMODE(p.stat().st_mode)


def test_bootstrap_layout_and_permissions(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    f.ensure()
    for d in ("", "notes", "generated", "archive"):
        assert mode(mem_dir / d) == 0o700
    assert mode(mem_dir / "README.md") == 0o600
    assert "Keep this folder private" in (mem_dir / "README.md").read_text()


def test_note_path_rejects_traversal(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    for bad in ("../x", "a/b", "..", ".x"):
        with pytest.raises(VpsMcpError):
            f.note_path(bad)


def test_atomic_write_leaves_no_temp_and_is_private(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    f.ensure()
    f.write_note(Note(name="a", type="fact", title="A", body="b"))
    files = sorted(p.name for p in (mem_dir / "notes").iterdir())
    assert files == ["a.md"]
    assert mode(mem_dir / "notes" / "a.md") == 0o600


def test_load_all_reports_malformed_symlinks_and_mismatches(mem_dir: Path, tmp_path: Path) -> None:
    outside = tmp_path / "outside.md"
    outside.write_text(note_text("outside"))
    seed_notes(
        mem_dir,
        {
            "good": note_text("good"),
            "broken": "---\nname: broken\nno closing",
            "renamed": note_text("other-name"),
            "Bad_Name": note_text("x"),
        },
    )
    (mem_dir / "notes" / "link.md").symlink_to(outside)
    (mem_dir / "notes" / ".hidden.md").write_text(note_text("hidden"))
    loaded = MemoryFolder(mem_dir).load_all()
    assert sorted(n.name for n in loaded.notes) == ["good", "renamed"]
    reasons = {m.file: m.reason for m in loaded.malformed}
    assert set(reasons) == {"notes/broken.md", "notes/link.md", "notes/Bad_Name.md"}
    assert "symlink" in reasons["notes/link.md"]
    assert loaded.mismatches == ["renamed"]


def test_read_note_does_not_follow_symlink(mem_dir: Path, tmp_path: Path) -> None:
    outside = tmp_path / "secret.md"
    outside.write_text(note_text("secret"))
    seed_notes(mem_dir, {})
    (mem_dir / "notes" / "secret.md").symlink_to(outside)
    with pytest.raises(VpsMcpError) as e:
        MemoryFolder(mem_dir).read_note("secret")
    assert e.value.category.value == "failed"


def test_write_through_symlink_refused(mem_dir: Path, tmp_path: Path) -> None:
    target = tmp_path / "victim.txt"
    target.write_text("keep")
    f = MemoryFolder(mem_dir)
    f.ensure()
    (mem_dir / "notes" / "v.md").symlink_to(target)
    with pytest.raises(VpsMcpError):
        f.write_note(Note(name="v", type="fact", title="t"))
    assert target.read_text() == "keep"


def test_symlinked_notes_dir_is_refused(mem_dir: Path, tmp_path: Path) -> None:
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    mem_dir.mkdir()
    (mem_dir / "notes").symlink_to(elsewhere)
    with pytest.raises(VpsMcpError):
        MemoryFolder(mem_dir).ensure()
    assert MemoryFolder(mem_dir).load_all().notes == []


def test_archive_moves_with_timestamp(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    f.ensure()
    seed_notes(mem_dir, {"old": note_text("old")})
    rel = f.archive("old")
    assert rel.startswith("archive/old.") and rel.endswith(".md")
    assert not (mem_dir / "notes" / "old.md").exists()
    assert (mem_dir / rel).exists()
    assert f.counts()["archived"] == 1


@pytest.mark.skipif(os.geteuid() == 0, reason="root ignores permissions")
def test_unwritable_folder(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    f.ensure()
    os.chmod(mem_dir / "notes", 0o500)
    try:
        assert f.writable_fs() is False
        with pytest.raises(VpsMcpError) as e:
            f.write_note(Note(name="a", type="fact", title="t"))
        assert e.value.category.value == "failed"
    finally:
        os.chmod(mem_dir / "notes", 0o700)


def test_write_generated_only_on_change(mem_dir: Path) -> None:
    f = MemoryFolder(mem_dir)
    f.ensure()
    assert f.write_generated("x.md", "<!-- generated by vps-mcp at 1 -->\nsame\n") is True
    assert f.write_generated("x.md", "<!-- generated by vps-mcp at 2 -->\nsame\n") is False
    assert f.write_generated("x.md", "<!-- generated by vps-mcp at 3 -->\nnew\n") is True
    with pytest.raises(VpsMcpError):
        f.write_generated("../escape.md", "x")
